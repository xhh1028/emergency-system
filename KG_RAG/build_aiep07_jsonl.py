def step_table(title, lead_in, rows, pages, owner_header=True):
    """Whole-flow `procedure` parent + one `procedure_step` child per row."""
    lines = [lead_in] if lead_in else []
    for no, owner, act in rows:
        if owner_header and owner:
            lines.append("步骤：%s；负责人员：%s；行动：%s" % (no, owner, act))
        else:
            lines.append("步骤：%s；行动：%s" % (no, act))
    specs = [{"title": title, "type": "procedure", "content": "\n".join(lines),
              "parent": None, "pages": pages}]
    for no, owner, act in rows:
        if owner_header and owner:
            c = "步骤：%s；负责人员：%s；行动：%s" % (no, owner, act)
        else:
            c = "步骤：%s；行动：%s" % (no, act)
        specs.append({"title": "%s-步骤%s" % (title, no), "type": "procedure_step",
                      "content": c, "parent": 0, "pages": pages})
    return specs


def append_step_table(dst, title, lead_in, rows, pages, owner_header=True):
    """Append a step table to an existing chunk list, rebasing child parent
    indices onto `dst`.

    step_table() marks every child with parent == 0, meaning "the procedure
    chunk is element 0 of the list I returned". Appending that list to a
    non-empty `dst` shifts the parent's real index, so children must be rebased
    by the offset - otherwise they silently point at whatever chunk happened to
    occupy index 0 of `dst`.
    """
    offset = len(dst)
    specs = step_table(title, lead_in, rows, pages, owner_header)
    for s in specs:
        if s["parent"] is not None:
            s["parent"] += offset
    dst += specs
    return dst


