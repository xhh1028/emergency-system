for sec, chunks, ver in FILES:
    recs = []
    for i, ch in enumerate(chunks, start=1):
        rec = {
            "chunk_id": "%s_%s_%03d" % (DOC_ID, sec, i),
            "doc_id": DOC_ID,
            "section": ch["section"],
            "title": ch["title"],
            "type": ch["type"],
            "content": ch["content"],
            "source_page": ch["source_page"],
            "printed_page": ch["printed_page"],
            "version": ver,
            "effective_date": EFFECTIVE_DATE,
            "parent_id": ch["parent_id"],
        }
        recs.append(rec)
    # 1C2/1C3 children name their parent by a hardcoded id. Fail loudly at build
    # time if such an id does not resolve to a chunk in the same file, rather
    # than emitting a dangling reference.
    file_ids = {r["chunk_id"] for r in recs}
    for r in recs:
        if r["parent_id"] is not None and r["parent_id"] not in file_ids:
            raise SystemExit("%s: parent_id %s does not resolve within this file"
                             % (r["chunk_id"], r["parent_id"]))
    out = OUT_DIR / ("%s_%s_chunks.jsonl" % (DOC_ID, sec))
    out.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in recs) + "\n",
                   encoding="utf-8")
    print("%-28s %3d chunks" % (out.name, len(chunks)))

print("total: %d chunks" % sum(len(c) for _, c, _ in FILES))
